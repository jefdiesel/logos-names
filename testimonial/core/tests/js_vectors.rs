//! Test vectors for the Basecamp Testimonial mini-app (`apps/testimonial`), which builds the
//! same `Post` message, seeds and PDA addresses in JavaScript (the QML engine has no Rust).
//!
//! The vectors live in `apps/testimonial/test/vectors.json`; the app's Node test
//! (`node apps/testimonial/logic.test.mjs`) checks its JavaScript against the same file. This
//! test checks the file against this crate, so both sides agree with the program.
//!
//! Regenerate with `WRITE_VECTORS=1 cargo test -p testimonial_core --test js_vectors`.

use borsh::BorshSerialize;
use lee_core::account::AccountId;
use serde_json::{Value, json};
use testimonial_core::{
    Head, Instruction, Message, SCHEMA, Testimonial, head_address, head_seed, node_address, node_seed,
};

const FILE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../apps/testimonial/test/vectors.json");

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn bytes<T: BorshSerialize>(value: &T) -> Vec<u8> {
    borsh::to_vec(value).expect("borsh")
}

/// One case: everything the app computes for a post, and two records it decodes.
fn case(program: AccountId, author: AccountId, submission: &str, username: Option<&str>, text: &str, now: u64) -> Value {
    let message = Message::Instruction(Instruction::Post {
        submission: submission.into(),
        username: username.map(Into::into),
        text: text.into(),
        now,
    });
    let head_seed = head_seed(submission);
    let node_seed = node_seed(submission, &author);
    let node = node_address(&program, submission, &author);
    let head = Head {
        schema: SCHEMA,
        submission: submission.into(),
        count: 3,
        newest: Some(node),
        first_at: now.saturating_sub(86_400_000),
        last_at: now,
    };
    let testimonial = Testimonial {
        schema: SCHEMA,
        submission: submission.into(),
        author,
        seq: 2,
        at: now,
        username: username.map(Into::into),
        text: text.into(),
        prev: Some(head_address(&program, submission)),
    };
    let first = Testimonial { seq: 0, prev: None, ..testimonial.clone() };
    json!({
        "program": program.to_string(),
        "author": author.to_string(),
        "submission": submission,
        "username": username,
        "text": text,
        "now": now,
        "message_hex": hex(&bytes(&message)),
        "head_seed_hex": hex(head_seed.as_bytes()),
        "node_seed_hex": hex(node_seed.as_bytes()),
        "head": head_address(&program, submission).to_string(),
        "node": node.to_string(),
        "accounts_json": format!("[{{\"seed\":\"{}\"}},{{\"seed\":\"{}\"}}]", hex(head_seed.as_bytes()), hex(node_seed.as_bytes())),
        "head_record_hex": hex(&bytes(&head)),
        "testimonial_record_hex": hex(&bytes(&testimonial)),
        "first_record_hex": hex(&bytes(&first)),
    })
}

fn vectors() -> Value {
    let counting: [u8; 32] = std::array::from_fn(|i| i as u8); // leading zero byte → a leading '1'
    let zeros_then: [u8; 32] = std::array::from_fn(|i| if i < 3 { 0 } else { 0xff - i as u8 });
    let long = "Names Wallet signs for me, and the app never saw a key. ".repeat(6); // > 255 bytes
    json!({
        "about": "Generated by testimonial/core/tests/js_vectors.rs; checked by it and by apps/testimonial/logic.test.mjs",
        "clock": {
            "program": AccountId::from_builtin_program_name(b"clock").to_string(),
            "account": AccountId::new(*b"/LEZ/ClockProgramAccount/0000001").to_string(),
        },
        "cases": [
            case(AccountId::new([7; 32]), AccountId::new([1; 32]), "lp-0021:names-wallet", Some("alice"), "Names Wallet is great", 1_800_000_000_000),
            case(AccountId::new(counting), AccountId::new(zeros_then), "lp-0021/names-wallet", None, "Ünïcode ✓ works\nline two\ttabbed", 1_793_735_537_880),
            case(AccountId::new(zeros_then), AccountId::new([0xfe; 32]), "a", Some("Grace Hopper ⚓"), &long, 1),
        ],
    })
}

#[test]
fn the_apps_vectors_match_the_program() {
    let made = vectors();
    if std::env::var_os("WRITE_VECTORS").is_some() {
        std::fs::write(FILE, serde_json::to_string_pretty(&made).unwrap() + "\n").expect("write the vectors");
        println!("wrote {FILE}");
        return;
    }
    let saved: Value = serde_json::from_str(&std::fs::read_to_string(FILE).expect("the vectors file (WRITE_VECTORS=1 makes it)"))
        .expect("vectors are JSON");
    assert_eq!(saved, made, "apps/testimonial/test/vectors.json is out of date: rerun with WRITE_VECTORS=1");
}
