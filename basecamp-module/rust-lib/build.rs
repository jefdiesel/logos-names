// The builder (logos-module-builder) puts the scaffold its lidl-gen generated at
// generated/provider_gen.rs before cargo runs. This copies it to OUT_DIR with its instance lock
// taken by try_lock (scaffold_patch.rs), and lib.rs includes that copy. The change is checked
// here (each site found exactly once, none left unchanged) and printed, so every build log shows
// the three sites; a generator that changed fails the build instead of building unpatched.
// Unit tests build without the scaffold: then nothing is generated and lib.rs includes nothing.

include!("scaffold_patch.rs");

fn main() {
    let dir = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let generated = dir.join("generated").join("provider_gen.rs");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("provider_gen.rs");
    println!("cargo:rerun-if-changed=generated/provider_gen.rs");
    println!("cargo:rerun-if-changed=scaffold_patch.rs");
    println!("cargo:rerun-if-changed=build.rs");
    let text = match std::fs::read_to_string(&generated) {
        Ok(text) => text,
        Err(_) => {
            // Only unit tests build without it, and they don't include it; a module build that
            // got here without one stops at this line instead of building with no scaffold.
            std::fs::write(&out, "compile_error!(\"generated/provider_gen.rs is missing: the scaffold is generated by the module builder\");\n").unwrap();
            return;
        }
    };
    let patched = patch_scaffold(&text).unwrap_or_else(|why| panic!("names scaffold patch: {why}"));
    for (number, line) in patched.lines().enumerate().filter(|(_, line)| line.contains("INSTANCE.0.try_lock()")) {
        println!("cargo:warning=names scaffold patch: provider_gen.rs:{}: {}", number + 1, line.trim());
    }
    println!("cargo:rustc-env=NAMES_SCAFFOLD_TRY_LOCK_SITES={}", patched.matches("INSTANCE.0.try_lock()").count());
    std::fs::write(&out, patched).unwrap();
}
